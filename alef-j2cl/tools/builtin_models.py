#!/usr/bin/env python3
"""Compile pinned XML9 accessory models into browser-readable model data.

These are real ALEF models, retaining their persistent concept/member/node IDs.
No desktop filesystem or model persistence implementation is needed at runtime.
"""
import json
from pathlib import Path
import re
import uuid
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MODELS = ['alef/languages/objecten/languageModels/gegevensspraak/base.mps',
          'alef/solutions/standaardFuncties/models/standaard.funcs.mps',
          'alef/languages/regelspraak/languageModels/regelspraak.dummyslots.mps',
          'alef/languages/servicespraak/models/servicespraak.dummyslots.mps',
          'alef/languages/validatie/languageModels/testspraak.dummyslots.mps']
ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyz$_ABCDEFGHIJKLMNOPQRSTUVWXYZ'


def node_id(encoded):
    value = 0
    for ch in encoded:
        value = (value << 6) | ALPHABET.index(ch)
    return value if value < 2**63 else value - 2**64


def main():
    language_imports()
    registrations, builders = [], []
    count = 0
    for index, path in enumerate(MODELS):
        xml = ET.parse(ROOT / path).getroot()
        assert xml.find('persistence').get('version') == '9'
        assert not list(xml.find('imports')), 'Explicitly support imported models before adding them'
        model_id, name = re.fullmatch(r'(r:[^()]+)\((.*)\)', xml.get('ref')).groups()
        registrations.append(f'    solution.registerModel(new BuiltinModel(solution, {json.dumps(model_id)}, {json.dumps(name)}, {index}));')
        concepts, members = {}, {}
        for lang in xml.findall('registry/language'):
            identity = uuid.UUID(lang.get('id')).int
            ids = f'0x{identity >> 64:x}L, 0x{identity & (2**64-1):x}L'
            for concept in lang.findall('concept'):
                prefix = f'{ids}, {concept.get("id")}L'
                concepts[concept.get('index')] = f'MetaAdapterFactory.getConcept({prefix}, {json.dumps(concept.get("name"))})'
                for member in concept:
                    kind = {'property': 'Property', 'child': 'ContainmentLink', 'reference': 'ReferenceLink'}[member.tag]
                    members[member.get('index')] = f'MetaAdapterFactory.get{kind}({prefix}, {member.get("id")}L, {json.dumps(member.get("name"))})'
        nodes = list(xml.iter('node'))
        names = {n.get('id'): f'n{i}' for i, n in enumerate(nodes)}
        lines = [f'  private static void build{index}(jetbrains.mps.smodel.SModel model) {{']
        for n in nodes:
            var = names[n.get('id')]
            lines.append(f'    SNode {var} = new SNode({concepts[n.get("concept")]}, new SNodeId.Regular({node_id(n.get("id"))}L));')
            for prop in n.findall('property'):
                lines.append(f'    {var}.setProperty({members[prop.get("role")]}, {json.dumps(prop.get("value"))});')
        for n in nodes:
            var = names[n.get('id')]
            for child in n.findall('node'):
                lines.append(f'    {var}.addChild({members[child.get("role")]}, {names[child.get("id")]});')
            for ref in n.findall('ref'):
                assert ref.get('node') in names, f'Unresolved builtin reference in {path}: {ET.tostring(ref)}'
                lines.append(f'    {var}.setReferenceTarget({members[ref.get("role")]}, {names[ref.get("node")]});')
        for n in xml.findall('node'):
            lines.append(f'    model.addRootNode({names[n.get("id")]});')
        lines.append('  }')
        builders.append('\n'.join(lines))
        count += len(nodes)
    code = '''package alefj2cl;
import java.util.UUID;
import jetbrains.mps.project.*;
import jetbrains.mps.project.structure.modules.SolutionDescriptor;
import jetbrains.mps.smodel.*;
import jetbrains.mps.smodel.adapter.structure.MetaAdapterFactory;
import jetbrains.mps.smodel.loading.ModelLoadingState;
import org.jetbrains.mps.openapi.persistence.NullDataSource;
/** Generated by tools/builtin_models.py from pinned ALEF accessory models. */
public final class AlefStandardModels {
  private AlefStandardModels() {}
  public static void install(Project project) {
    SolutionDescriptor descriptor = new SolutionDescriptor();
    descriptor.setId(ModuleId.regular(UUID.fromString("8270cb09-651a-458a-9f4e-86e3e4423c92")));
    descriptor.setNamespace("alefj2cl.standardModels");
    if (project.getRepository().getModule(descriptor.getId()) != null) return;
    Solution solution = new Solution(descriptor, null) { @Override public boolean isPackaged() { return true; } };
    project.addModule(solution);
''' + '\n'.join(registrations) + '''
  }
  private static final class BuiltinModel extends EditableModelDescriptor {
    private final int index;
    BuiltinModel(Solution solution, String id, String name, int index) {
      super(new SModelReference(solution.getModuleReference(), SModelId.fromString(id), name), new NullDataSource());
      this.index = index;
    }
    @Override protected ModelLoadResult<jetbrains.mps.smodel.SModel> createModel() {
      jetbrains.mps.smodel.SModel model = new jetbrains.mps.smodel.SModel(getReference());
      switch (index) {
''' + '\n'.join(f'        case {i}: build{i}(model); break;' for i in range(len(MODELS))) + '''
        default: throw new IllegalArgumentException("Unknown standard model");
      }
      return new ModelLoadResult<>(model, ModelLoadingState.FULLY_LOADED);
    }
    @Override public boolean isReadOnly() { return true; }
    @Override public void save() { throw new UnsupportedOperationException("Read-only ALEF standard model"); }
    @Override public void reloadFromSource() { throw new UnsupportedOperationException("Compiled ALEF standard model"); }
  }
''' + '\n'.join(builders) + '\n}\n'
    (ROOT / 'browser-src/alefj2cl/AlefStandardModels.java').write_text(code)
    print(f'Compiled {len(MODELS)} ALEF standard models with {count} nodes')


def language_imports():
    """Preserve model imports when compiled languages have no source module."""
    profile = set(json.loads((ROOT / 'out/source-inventory.json').read_text())['languages'])
    files = subprocess.check_output(['git', '-C', str(ROOT / 'alef'), 'ls-files', '*.mpl'], text=True).splitlines()
    cases = []
    for relative in files:
        path = ROOT / 'alef' / relative
        descriptor = ET.parse(path).getroot()
        namespace = descriptor.get('namespace')
        if namespace not in profile:
            continue
        imports = {}
        for model_root in descriptor.findall('models/modelRoot'):
            assert model_root.get('contentPath') == '${module}'
            for source_root in model_root.findall('sourceRoot'):
                for model_file in sorted((path.parent / source_root.get('location')).rglob('*.mps')):
                    for language in ET.parse(model_file).getroot().findall('languages/use'):
                        imports[language.get('id')] = language.get('name')
        values = []
        for identity, name in sorted(imports.items()):
            bits = uuid.UUID(identity).int
            values.append(f'MetaAdapterFactory.getLanguage(0x{bits >> 64:x}L, 0x{bits & (2**64-1):x}L, {json.dumps(name)})')
        cases.append(f'      case {json.dumps(namespace)}: return java.util.Arrays.asList(' + ', '.join(values) + ');')
    code = '''package alefj2cl;
import java.util.Collection;
import org.jetbrains.mps.openapi.language.SLanguage;
import jetbrains.mps.smodel.adapter.structure.MetaAdapterFactory;
/** Generated model-language imports, preserving completion filters without source modules. */
public final class BrowserLanguageImports {
  private BrowserLanguageImports() {}
  public static Collection<SLanguage> importedLanguages(SLanguage language) {
    switch (language.getQualifiedName()) {
''' + '\n'.join(cases) + '''
      default: return java.util.Collections.emptyList();
    }
  }
}
'''
    (ROOT / 'browser-src/alefj2cl/BrowserLanguageImports.java').write_text(code)


if __name__ == '__main__':
    main()
