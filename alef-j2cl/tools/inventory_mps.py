#!/usr/bin/env python3
"""Resolve supplemental MPS runtime sources against existing browser providers."""
import ast
import collections
import json
from pathlib import Path
import re
import subprocess
from inventory import code_only

ROOT = Path(__file__).resolve().parents[1]
MPS = ROOT.parent / 'mps-j2cl'
EXCLUDED = ('plugins/mps-vcs/', 'plugins/mps-httpsupport/', 'workbench/mps-ui/',
            'core/generator/', 'workbench/mps-workbench/', 'core/persistence/')


def main():
    index = {}
    paths = subprocess.check_output(['git', '-C', str(MPS / 'mps'), 'ls-files', '*.java'], text=True).splitlines()
    def fqname(path):
        for prefix in ('/jetbrains/', '/org/', '/com/'):
            if prefix in path:
                return path[path.index(prefix) + 1:-5].replace('/', '.')
    for path in paths:
        name = fqname(path)
        if name and (name not in index or '/source_gen/' in path):
            index[name] = path
    existing = set()
    for file in ('mps-browser-projects.bzl', 'financial-sources.bzl'):
        existing.update(fqname(p) for p in re.findall(r'"([^"]+\.java)"', (MPS / file).read_text()))
    # IntelliJ support and browser-specific MPS providers are already linked.
    for path in (MPS / 'third_party/intellij-stubs/src').rglob('*.java'):
        text = path.read_text()
        package = re.search(r'^package\s+([\w.]+);', text, re.M)
        if package:
            existing.add(package[1] + '.' + path.stem)
    report = json.loads((ROOT / 'out/source-inventory.json').read_text())
    roots = set()
    extension_report = json.loads((ROOT / 'out/extension-inventory.json').read_text())
    language_roots = json.loads((ROOT / 'out/mps-language-profiles.json').read_text())['roots']
    for name in list(report['external_imports']) + extension_report['external_imports'] + language_roots:
        while '.' in name and name not in index:
            name = name.rsplit('.', 1)[0]
        if name in index and name not in existing:
            roots.add(name)
    selected, unresolved, parents, overrides = set(), set(), {}, {}
    pending = collections.deque(sorted(roots))
    while pending:
        name = pending.popleft()
        if name in selected or name in existing:
            continue
        relative = index[name]
        if relative.startswith(EXCLUDED):
            unresolved.add(name)
            continue
        selected.add(name)
        replacement = ROOT / 'j2cl-src/mps' / relative
        if replacement.exists():
            overrides[relative] = replacement.relative_to(ROOT).as_posix()
        text = code_only((replacement if replacement.exists() else MPS / 'mps' / relative).read_text())
        package = name.rsplit('.', 1)[0]
        refs = re.findall(r'^import\s+(?:static\s+)?([\w.$*]+);', text, re.M)
        tokens = set(re.findall(r'\b[A-Za-z_$][\w$]*\b', text))
        refs += [package + '.' + token for token in tokens]
        refs += re.findall(r'\b(?:jetbrains|org|com)\.[\w.$]+', text)
        for ref in list(refs):
            if ref.endswith('.*'):
                refs += [ref[:-1] + token for token in tokens]
        for ref in refs:
            while '.' in ref and ref not in index:
                ref = ref.rsplit('.', 1)[0]
            if ref in index and ref not in existing and ref not in selected:
                pending.append(ref)
                parents.setdefault(ref, name)
    link = ROOT / '.work/mps-src'
    if not link.exists():
        link.symlink_to(MPS / 'mps', target_is_directory=True)
    sources = sorted(overrides.get(index[n], '.work/mps-src/' + index[n]) for n in selected)
    (ROOT / 'mps-sources.bzl').write_text('# Generated by tools/inventory_mps.py\nMPS_SOURCES = ' + json.dumps(sources, indent=4) + '\n')
    (ROOT / 'out/mps-inventory.json').write_text(json.dumps({'sources': sources, 'roots': sorted(roots), 'parents': parents, 'unresolved': sorted(unresolved), 'overrides': overrides}, indent=2) + '\n')
    print('Supplemental MPS:', len(sources), 'sources;', len(unresolved), 'desktop dependencies require review')


if __name__ == '__main__':
    main()
