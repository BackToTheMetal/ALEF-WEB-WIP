#!/usr/bin/env python3
"""Add the source closure required beyond the sibling's selected runtimes."""
import ast
import collections
import json
from pathlib import Path
import re
from inventory import code_only

ROOT = Path(__file__).resolve().parents[1]
EXT = ROOT.parent / 'mps-extensions-j2cl'


def main():
    source_manifest = json.loads((EXT / 'upstream-sources.json').read_text())
    index = {entry['path'].split('/', 2)[2][:-5].replace('/', '.'): entry['path']
             for entry in source_manifest if entry['path'].endswith('.java')}
    tree = ast.parse((EXT / 'runtime-sources.bzl').read_text())
    groups = next(ast.literal_eval(node.value) for node in tree.body if isinstance(node, ast.Assign) and node.targets[0].id == 'RUNTIME_SOURCES')
    existing = set()
    for paths in groups.values():
        for relative in paths:
            match = re.search(r'^package\s+([\w.]+);', (EXT / relative).read_text(), re.M)
            if match:
                existing.add(match[1] + '.' + Path(relative).stem)
    report = json.loads((ROOT / 'out/source-inventory.json').read_text())
    roots = set(report['external_imports']) & set(index) - existing
    pending = collections.deque(sorted(roots))
    selected, parents, overrides, external = set(), {}, {}, set()
    def resolve(name):
        while '.' in name:
            if name in index:
                return name
            name = name.rsplit('.', 1)[0]
        return None
    while pending:
        name = pending.popleft()
        if name in selected or name in existing:
            continue
        selected.add(name)
        original = EXT / index[name]
        replacement = ROOT / 'j2cl-src/extensions' / index[name].removeprefix('upstream-src/')
        if replacement.exists():
            overrides[index[name]] = replacement.relative_to(ROOT).as_posix()
        text = code_only((replacement if replacement.exists() else original).read_text())
        package = name.rsplit('.', 1)[0]
        references = re.findall(r'^import\s+(?:static\s+)?([\w.$]+);', text, re.M)
        external.update(ref for ref in references if not resolve(ref))
        references += re.findall(r'\b(?:de|com)\.[\w.$]+', text)
        references += [package + '.' + token for token in set(re.findall(r'\b[A-Za-z_$][\w$]*\b', text))]
        for ref in references:
            target = resolve(ref)
            if target and target not in selected and target not in existing:
                pending.append(target)
                parents.setdefault(target, name)
    link = ROOT / '.work/extensions-src'
    if not link.exists():
        link.symlink_to(EXT / 'upstream-src', target_is_directory=True)
    paths = sorted(overrides.get(index[name], '.work/extensions-src/' + index[name].removeprefix('upstream-src/')) for name in selected)
    (ROOT / 'extension-sources.bzl').write_text('# Generated by tools/inventory_extensions.py\nEXTENSION_SOURCES = ' + json.dumps(paths, indent=4) + '\n')
    (ROOT / 'out/extension-inventory.json').write_text(json.dumps({'roots': sorted(roots), 'sources': paths, 'parents': parents, 'overrides': overrides, 'external_imports': sorted(external)}, indent=2) + '\n')
    print('Supplemental MPS extensions:', len(paths), 'Java sources')


if __name__ == '__main__':
    main()
