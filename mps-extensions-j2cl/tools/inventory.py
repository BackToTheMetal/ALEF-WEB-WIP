"""Generate explicit per-runtime source selections; no Bazel metadata in upstream trees."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
MODULES = {
    'reflection': 'de.slisson.mps.reflection.runtime',
    'hacks': 'de.slisson.mps.hacks.editor',
    'querylist': 'com.mbeddr.mpsutil.editor.querylist.runtime',
    'boolean_editor': 'de.itemis.mps.editor.bool.runtime',
    'math_editor': 'de.itemis.mps.editor.math.runtime',
    'math_symbols': 'de.itemis.mps.editor.math.symbols',
    'grammarcells': 'com.mbeddr.mpsutil.grammarcells.runtime',
    'grammarcells_language': 'com.mbeddr.mpsutil.grammarcells.runtimelang',
}
excluded = []
sources = {}
for target, module in MODULES.items():
    base = ROOT / 'upstream-src' / module
    selected = []
    for path in sorted(base.rglob('*.java')):
        relative = path.relative_to(base)
        reason = None
        if target == 'querylist' and path.name == 'QueriesUtil.java':
            reason = 'Generator-time TemplateQueryContext helper, not editor runtime'
        if 'plugin' in relative.parts and path.name != 'ParserFailureNotifier.java':
            reason = 'Desktop IntelliJ plugin integration and model checker'
        if 'insertpopup' in relative.parts and path.name not in ('CellActionExecuter.java', 'CellActionExecutorFinder.java', 'SubstituteActionAsCellAction.java'):
            reason = 'Desktop IntelliJ popup integration'
        if reason:
            excluded.append({'source': path.relative_to(ROOT).as_posix(), 'reason': reason})
            continue
        replacement = ROOT / 'j2cl-src' / relative
        selected.append((replacement if replacement.exists() else path).relative_to(ROOT).as_posix())
    assert selected, module
    if target == 'math_editor':
        selected.append('j2cl-src/de/itemis/mps/editor/math/runtime/MathRuntimeLanguage.java')
    if target == 'grammarcells':
        selected.append('j2cl-src/com/mbeddr/mpsutil/grammarcells/runtime/GrammarCellsRuntime.java')
    sources[target] = selected
(ROOT / 'runtime-sources.bzl').write_text('"""Generated by tools/inventory.py; explicit browser runtime sources."""\nRUNTIME_SOURCES = ' + json.dumps(sources, indent=4) + '\n')
(ROOT / 'excluded-sources.json').write_text(json.dumps(excluded, indent=2) + '\n')
print({k: len(v) for k, v in sources.items()})
