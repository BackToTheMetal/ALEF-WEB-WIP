import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
process.chdir(root);
fs.mkdirSync('out/dist',{recursive:true});
const archive='out/dist/mps-xml-compat-0.1.0.tar.gz';
const entries=['src','BUILD.bazel','MODULE.bazel','MODULE.bazel.lock','.bazelversion','.bazelrc','third_party','README.md','IMPLEMENTATION_STATUS.md','compatibility','integration'];
execFileSync('tar',['-czf',archive,...entries]);
const sha256=createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(archive+'.sha256',sha256+'  '+path.basename(archive)+'\n');
const extracted=path.resolve(root,'out/consumer-dependency');
if(path.dirname(extracted)!==path.join(root,'out'))throw new Error('Unsafe artifact extraction path');
fs.rmSync(extracted,{recursive:true,force:true});
fs.mkdirSync(extracted,{recursive:true});
execFileSync('tar',['-xzf',archive,'-C','out/consumer-dependency']);
fs.cpSync('examples/consumer','out/fresh-consumer',{recursive:true});
for(const name of ['.bazelversion','.bazelrc'])fs.copyFileSync(name,'out/fresh-consumer/'+name);
console.log(`Source artifact: ${archive}\nSHA-256: ${sha256}`);
