#!/usr/bin/env python3
"""Generate/check SModelName's golden results using untouched MPS and its resource bundle."""

import argparse
import difflib
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests/openapi"


def boundary_source(snapshot):
    candidates = set(range(256)) | {0xD7FF, 0xD800, 0xDBFF, 0xDC00, 0xDFFF, 0xE000, 0x10FFFF}
    for field in ("start", "part"):
        for boundary in snapshot[field]:
            candidates.update(cp for cp in (boundary - 1, boundary, boundary + 1) if 0 <= cp <= 0x10FFFF)
    values = sorted(candidates)
    lines = ["      " + ", ".join(str(cp) for cp in values[index:index + 16]) + ","
             for index in range(0, len(values), 16)]
    return ("package mpsj2cl.openapi;\n\n"
            "// Generated by tools/run_openapi_oracle.py from compatibility/java-identifiers.json.\n"
            "final class IdentifierBoundaryCases {\n"
            "  static final int[] CODEPOINTS = {\n" + "\n".join(lines) +
            "\n  };\n  private IdentifierBoundaryCases() {}\n}\n")


def save_or_check(path, text, check):
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"Stale oracle artifact: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def run_variant(args, variant):
    output = ROOT / ".work/openapi-oracle" / variant
    output.mkdir(parents=True, exist_ok=True)
    source_root = ROOT / "mps/core/openapi/source"
    source = (ROOT / ("mps" if variant == "upstream" else "mps-web") /
              "core/openapi/source/org/jetbrains/mps/openapi/model/SModelName.java")
    sources = [source, TESTS / "SModelNameTest.java", TESTS / "IdentifierBoundaryCases.java"]
    subprocess.run([args.javac, "--release", "21", "-encoding", "UTF-8", "-d", str(output),
                    "-cp", str(args.annotations_jar), "-sourcepath", str(source_root),
                    *map(str, sources)], check=True)
    classpath = os.pathsep.join(map(str, (output, ROOT / "mps/core/resources_en/source", args.annotations_jar)))
    return subprocess.check_output([args.java, "-Duser.language=en", "-Duser.country=US",
                                    "-cp", classpath, "mpsj2cl.openapi.SModelNameTest"], text=True, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--annotations-jar", type=Path, required=True, help="Existing JetBrains annotations JVM JAR")
    parser.add_argument("--java", default="java")
    parser.add_argument("--javac", default="javac")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-overlay", action="store_true")
    args = parser.parse_args()
    args.annotations_jar = args.annotations_jar.resolve(strict=True)
    snapshot = json.loads((ROOT / "compatibility/java-identifiers.json").read_text(encoding="utf-8"))
    version_text = subprocess.run([args.java, "-version"], text=True, capture_output=True, check=True).stderr
    version = re.search(r'version "([^"]+)"', version_text)
    if not version or version[1] != snapshot["java_version"]:
        raise SystemExit(f"Oracle requires java.version {snapshot['java_version']}; received {version_text.strip()}")
    save_or_check(TESTS / "IdentifierBoundaryCases.java", boundary_source(snapshot), args.check)
    expected = run_variant(args, "upstream")
    save_or_check(TESTS / "jvm-expected.txt", expected, args.check)
    baseline = {
        "java_version": snapshot["java_version"],
        "mps_revision": subprocess.check_output(["git", "-C", str(ROOT / "mps"), "rev-parse", "HEAD"], text=True).strip(),
        "oracle_source": "mps/core/openapi/source/org/jetbrains/mps/openapi/model/SModelName.java",
        "oracle_resources": "mps/core/resources_en/source/jetbrains/mps/project/validation/CoreBundle.properties",
        "unicode_note": "Identifier behavior is pinned to this JDK 21 runtime; JDK 25 Unicode parity is not claimed.",
    }
    save_or_check(TESTS / "jvm-baseline.json", json.dumps(baseline, indent=2) + "\n", args.check)
    if args.verify_overlay:
        actual = run_variant(args, "overlay")
        if actual != expected:
            print("".join(difflib.unified_diff(expected.splitlines(True), actual.splitlines(True),
                                                fromfile="upstream JVM", tofile="overlay JVM")))
            raise SystemExit("SModelName overlay differs from the upstream JVM oracle")
    print(f"SModelName oracle: JDK {snapshot['java_version']}; {len(expected.splitlines())} result rows; "
          + ("overlay matches" if args.verify_overlay else "upstream golden verified"))


if __name__ == "__main__":
    main()
