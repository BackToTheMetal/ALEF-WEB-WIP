#!/usr/bin/env python3
"""Generate/check Java 21's nonspacing-mark ranges for exact regex boundaries."""
import argparse
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    scratch = ROOT / '.work/regex-unicode'
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch) as directory:
        subprocess.run(['javac', '--release', '21', '-d', directory, str(ROOT / 'tests/regex/RegexUnicodeDump.java')], check=True)
        snapshot = json.loads(subprocess.check_output(['java', '-cp', directory, 'RegexUnicodeDump'], text=True))
    if not snapshot['java_version'].startswith('21.'):
        raise SystemExit('Regex Unicode data must come from Java 21')
    table = snapshot['nonspacing_mark_ranges']
    rows = ['    ' + ', '.join(map(str, table[i:i+12])) + ',' for i in range(0, len(table), 12)]
    bases = snapshot['bmp_letter_digit_ranges']
    base_rows = ['    ' + ', '.join(map(str, bases[i:i+12])) + ',' for i in range(0, len(bases), 12)]
    source = '''package java.util.regex;

// Generated by tools/make_regex_unicode_data.py from Java VERSION.
final class JavaRegexUnicodeData {
  private JavaRegexUnicodeData() {}
  private static String characterClass(int[] table, boolean bmpOnly) {
    StringBuilder result = new StringBuilder("[");
    for (int i = 0; i < table.length; i += 2) {
      if (bmpOnly && table[i] > 0xFFFF) break;
      result.append("\\\\u{").append(Integer.toHexString(table[i])).append('}');
      if (table[i] != table[i + 1]) {
        result.append("-\\\\u{").append(Integer.toHexString(bmpOnly ? Math.min(0xFFFF, table[i + 1]) : table[i + 1])).append('}');
      }
    }
    return result.append(']').toString();
  }
  private static final int[] MARK_RANGES = {
ROWS
  };
  private static final int[] BASE_RANGES = {
BASE_ROWS
  };
  private static final String ASCII_WORD = "[a-zA-Z_0-9]";
  private static final String BMP_MARK = characterClass(MARK_RANGES, true);
  private static final String ANY_MARK = characterClass(MARK_RANGES, false);
  private static final String BMP_BASE = characterClass(BASE_RANGES, true);
  // Java 21 scans backwards by UTF-16 unit to locate a mark's letter/digit base.
  // An intervening supplementary character's low surrogate stops that scan.
  private static final String LEFT_WORD = "(?:(?<=" + ASCII_WORD + ")|(?<=" + BMP_BASE + BMP_MARK + "+))";
  private static final String RIGHT_WORD = "(?:(?=" + ASCII_WORD + ")|(?<=" + BMP_BASE + BMP_MARK + "*)(?=" + ANY_MARK + "))";
  static final String BOUNDARY = "(?:" + LEFT_WORD + "(?!" + RIGHT_WORD + ")|(?!" + LEFT_WORD + ")" + RIGHT_WORD + ")";
  static final String NON_BOUNDARY = "(?:" + LEFT_WORD + RIGHT_WORD + "|(?!" + LEFT_WORD + ")(?!" + RIGHT_WORD + "))";
}
'''.replace('VERSION', snapshot['java_version']).replace('BASE_ROWS', '\n'.join(base_rows)).replace('ROWS', '\n'.join(rows))
    outputs = {
        ROOT / 'compatibility/regex-unicode.json': json.dumps(snapshot, indent=2) + '\n',
        ROOT / 'third_party/j2cl/api-support/jre/java/java/util/regex/JavaRegexUnicodeData.java': source,
    }
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('Stale regex Unicode data: ' + str(path))
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'Regex Unicode data: {len(table)//2} nonspacing-mark ranges; Java {snapshot["java_version"]}')

if __name__ == '__main__':
    main()
