#!/usr/bin/env python3
"""Generate the Character adapter from a reviewed Java 21 property snapshot."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API = ROOT / "third_party/j2cl/api-support/jre/java"


def body(source, signature, replacement):
    anchor = "  public static " + signature + " {"
    if anchor not in source:
        return source.replace("public final class Character implements Comparable<Character>, Serializable {",
                              "public final class Character implements Comparable<Character>, Serializable {\n\n"
                              + anchor + "\n    " + replacement + "\n  }", 1)
    start = source.index(anchor)
    cursor = start + len(anchor)
    level = 1
    while level:
        if source[cursor] == "{": level += 1
        elif source[cursor] == "}": level -= 1
        cursor += 1
    return source[:start] + anchor + "\n    " + replacement + "\n  }" + source[cursor:]


def generate(snapshot):
    output = ["package javaemul.internal;\n\n",
              "// Generated by tools/make_character_data.py from Java " + snapshot["java_version"] + ".\n",
              "// Simple Unicode code-point mappings. Invalid code points retain their input mapping.\n",
              "public final class CharacterData {\n",
              "  private CharacterData() {}\n\n",
              "  private static int find(int[] table, int codePoint) {\n",
              "    int low = 0, high = table.length / 3 - 1;\n",
              "    while (low <= high) {\n",
              "      int middle = (low + high) >>> 1;\n",
              "      int at = middle * 3;\n",
              "      if (codePoint < table[at]) { high = middle - 1; }\n",
              "      else if (codePoint > table[at + 1]) { low = middle + 1; }\n",
              "      else { return at; }\n",
              "    }\n    return -1;\n  }\n\n",
              "  public static int properties(int codePoint) {\n",
              "    int index = find(PROPERTIES, codePoint);\n",
              "    return index < 0 ? 0 : PROPERTIES[index + 2];\n  }\n\n",
              "  private static int map(int[] table, int codePoint) {\n",
              "    int index = find(table, codePoint);\n",
              "    return index < 0 ? codePoint : codePoint + table[index + 2];\n  }\n\n",
              "  public static int toLowerCase(int cp) { return map(LOWER, cp); }\n",
              "  public static int toUpperCase(int cp) { return map(UPPER, cp); }\n",
              "  public static int toTitleCase(int cp) { return map(TITLE, cp); }\n\n",
              "  public static int digit(int codePoint, int radix) {\n",
              "    if (radix < 2 || radix > 36) { return -1; }\n",
              "    int index = find(DIGIT, codePoint);\n",
              "    if (index < 0) { return -1; }\n",
              "    int value = codePoint + DIGIT[index + 2];\n",
              "    return value < radix ? value : -1;\n  }\n\n",
              "  private static int[] join(int[][] parts) {\n",
              "    int size = 0;\n    for (int[] part : parts) { size += part.length; }\n",
              "    int[] result = new int[size];\n    int position = 0;\n",
              "    for (int[] part : parts) {\n",
              "      for (int value : part) { result[position++] = value; }\n",
              "    }\n    return result;\n  }\n\n"]
    for table in ("properties", "lower", "upper", "title", "digit"):
        values = snapshot[table]
        chunks = [values[index:index + 900] for index in range(0, len(values), 900)]
        output.append("  private static final int[] " + table.upper() + " = join(new int[][] {"
                      + ", ".join(table + str(index) + "()" for index in range(len(chunks))) + "});\n\n")
        for index, chunk in enumerate(chunks):
            output.append("  private static int[] " + table + str(index) + "() {\n    return new int[] {\n")
            for at in range(0, len(chunk), 12):
                output.append("      " + ", ".join(map(str, chunk[at:at + 12])) + ",\n")
            output.append("    };\n  }\n\n")
    output.append("}\n")
    return "".join(output)


def character_source():
    source = (ROOT / ".work/j2cl-20260402/jre/java/java/lang/Character.java").read_text(encoding="utf-8")
    source = source.replace("import javaemul.internal.NativeRegExp;", "import javaemul.internal.CharacterData;")
    source = source.replace("import javaemul.internal.StringUtil;\n", "")
    source = source.replace("  /*\n   * TODO: correct Unicode handling.\n   */\n", "")
    for field in ("digitRegex", "leterRegex", "isLeterOrDigitRegex"):
        source = source.replace("  private static NativeRegExp " + field + ";\n\n", "")
    methods = {"isDigit": 1, "isLetter": 2, "isLetterOrDigit": 3, "isLowerCase": 4,
               "isUpperCase": 8, "isTitleCase": 16, "isWhitespace": 32, "isSpaceChar": 64,
               "isJavaIdentifierStart": 128, "isJavaIdentifierPart": 256}
    # Normalize existing parameter names first, preserving unrelated source byte for byte.
    source = source.replace("isWhitespace(char ch)", "isWhitespace(char c)").replace("isSpaceChar(char ch)", "isSpaceChar(char c)")
    for name, mask in methods.items():
        source = body(source, "boolean " + name + "(char c)", "return " + name + "((int) c);")
        source = body(source, "boolean " + name + "(int codePoint)",
                      "return (CharacterData.properties(codePoint) & " + str(mask) + ") != 0;")
    for name in ("toLowerCase", "toUpperCase", "toTitleCase"):
        source = body(source, "char " + name + "(char c)", "return (char) CharacterData." + name + "(c);")
        source = body(source, "int " + name + "(int c)", "return CharacterData." + name + "(c);")
    source = body(source, "int digit(char c, int radix)", "return CharacterData.digit(c, radix);")
    source = body(source, "int digit(int codePoint, int radix)", "return CharacterData.digit(codePoint, radix);")
    # Replace the outdated class-level Unicode gap list, retaining the normal class introduction.
    begin = source.index(" * <p>TODO(jat):")
    end = source.index(" */\npublic final class Character", begin)
    source = source[:begin] + " * <p>Unicode classification and simple case mappings use generated Java 21 data.\n" + source[end:]
    return source


def boundary_source(snapshot):
    points = set(range(256)) | {-2147483648, -1, 0xd7ff, 0xd800, 0xdfff, 0xe000, 0x10ffff, 0x110000, 2147483647}
    for name in ("properties", "lower", "upper", "title", "digit"):
        table = snapshot[name]
        for index in range(0, len(table), 3):
            for boundary in (table[index], table[index + 1]):
                points.update(cp for cp in (boundary - 1, boundary, boundary + 1) if 0 <= cp <= 0x10ffff)
    values = sorted(points)
    chunks = [values[index:index + 900] for index in range(0, len(values), 900)]
    lines = ["package mpsj2cl.runtime;\n\n// Generated from every Java 21 Character table boundary.\n",
             "final class CharacterBoundaryCases {\n  static final int[][] CODEPOINTS = {"
             + ", ".join("part" + str(i) + "()" for i in range(len(chunks))) + "};\n"]
    for index, chunk in enumerate(chunks):
        lines.append("  private static int[] part" + str(index) + "() {\n    return new int[] {\n")
        for at in range(0, len(chunk), 12):
            lines.append("      " + ", ".join(map(str, chunk[at:at + 12])) + ",\n")
        lines.append("    };\n  }\n")
    lines.append("}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    snapshot = json.loads((ROOT / "compatibility/java-characters.json").read_text(encoding="utf-8"))
    outputs = {API / "javaemul/internal/CharacterData.java": generate(snapshot),
               API / "java/lang/Character.java": character_source(),
               ROOT / "tests/runtime_support/CharacterBoundaryCases.java": boundary_source(snapshot)}
    for file, text in outputs.items():
        if args.check:
            if file.read_text(encoding="utf-8") != text: raise SystemExit("Stale Character source: " + str(file))
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text, encoding="utf-8", newline="\n")
    print("Character adapter: Java " + snapshot["java_version"] + "; "
          + ", ".join(name + "=" + str(len(snapshot[name]) // 3) for name in ("properties", "lower", "upper", "title", "digit")))


if __name__ == "__main__":
    main()
