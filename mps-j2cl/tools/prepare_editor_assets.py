#!/usr/bin/env python3
"""Bundle the exact image resources referenced by the selected MPSIcons Java class."""
import argparse
import base64
import hashlib
import json
import re
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'mps/workbench/mps-icons/source'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    names = sorted({'/' + name.lstrip('/') for name in re.findall(r'load\("([^"]+)"\)', (BASE / 'jetbrains/mps/icons/MPSIcons.java').read_text())})
    rows, statements = [], []
    for name in names:
        file = BASE / name.lstrip('/')
        data = file.read_bytes()
        if file.suffix == '.png':
            if data[:8] != b'\x89PNG\r\n\x1a\n':
                raise SystemExit('Invalid PNG: ' + name)
            width, height = struct.unpack('>II', data[16:24])
            mime = 'image/png'
        elif file.suffix == '.svg':
            svg = ET.fromstring(data)
            width = int(float(svg.attrib['width'].removesuffix('px')))
            height = int(float(svg.attrib['height'].removesuffix('px')))
            mime = 'image/svg+xml'
        else:
            raise SystemExit('Unsupported editor asset: ' + name)
        if width <= 0 or height <= 0:
            raise SystemExit('Invalid image size: ' + name)
        uri = 'data:' + mime + ';base64,' + base64.b64encode(data).decode('ascii')
        statements.append('    icons.put(' + json.dumps(name) + ', new BrowserResourceIcon(' + str(width) + ', ' + str(height) + ', ' + json.dumps(uri) + '));')
        rows.append({'path': str(file.relative_to(ROOT)).replace('\\', '/'), 'name': name,
                     'width': width, 'height': height, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})
    source = '''// Generated by tools/prepare_editor_assets.py from pinned Apache-2.0 MPS assets.
package mpsj2cl.editor;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.swing.Icon;
final class BrowserMpsAssetData {
  static Map<String, Icon> create() {
    Map<String, Icon> icons = new LinkedHashMap<>();
''' + '\n'.join(statements) + '''
    return icons;
  }
}
'''
    outputs = {
        ROOT / 'browser/src/mpsj2cl/editor/BrowserMpsAssetData.java': source,
        ROOT / 'compatibility/editor-assets.json': json.dumps({'source': 'workbench/mps-icons', 'assets': rows}, indent=2) + '\n',
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                raise SystemExit('Stale editor assets: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'Editor assets: {len(rows)} images, {sum(row["bytes"] for row in rows)} source bytes')


if __name__ == '__main__':
    main()
