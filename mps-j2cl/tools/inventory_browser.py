#!/usr/bin/env python3
"""Resolve the explicitly selected browser sources without importing desktop projects implicitly."""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path, PurePosixPath
import sys

from inventory_mps import (ROOT, compilation_groups, dependency_closure, excluded,
                           project_sources, read_projects, source_revision, write_or_check)

PROFILE = ROOT / "compatibility/browser-profile.json"


def safe_path(value):
    p = PurePosixPath(value)
    return bool(value) and not p.is_absolute() and ".." not in p.parts and "\\" not in value and ":" not in value


def browser_projects(mps: Path, profile_path: Path = PROFILE):
    profile = json.loads(profile_path.read_text(encoding="utf-8"))
    upstream = read_projects(mps)
    projects = copy.deepcopy(upstream)
    for name, settings in profile["projects"].items():
        if name not in projects:
            raise ValueError(f"Unknown browser project: {name}")
        unknown = set(settings) - {"srcs", "deps", "libraries", "exported_deps", "exported_libraries", "bazel_deps", "reason", "resources"}
        if unknown:
            raise ValueError(f"Unknown profile fields for {name}: {sorted(unknown)}")
        if set(settings) & {"srcs", "deps", "libraries", "exported_deps", "exported_libraries"} and not settings.get("reason", "").strip():
            raise ValueError(f"Source/dependency selection needs a reason: {name}")
        for field in ("deps", "libraries", "exported_deps", "exported_libraries"):
            if field in settings:
                projects[name][field] = sorted(set(settings[field]))
        projects[name]["bazel_deps"] = settings.get("bazel_deps", [])
    selected = dependency_closure(projects, profile["roots"])
    for name in selected:
        info = projects[name]
        settings = profile["projects"].get(name, {})
        original = project_sources(mps, upstream[name])
        if "srcs" in settings:
            sources = settings["srcs"]
            if len(sources) != len(set(sources)):
                raise ValueError(f"Duplicate selected source in {name}")
            for path in sources:
                if not safe_path(path) or path not in original:
                    raise ValueError(f"Not an upstream Java source of {name}: {path}")
            info["selection"] = "explicit"
        else:
            sources = original
            kotlin = [p.relative_to(mps).as_posix() for r in info["src_roots"] for p in (mps / r).rglob("*.kt")
                      if not excluded(p.relative_to(mps).as_posix(), info["excludes"])]
            if kotlin:
                raise ValueError(f"{name} has {len(kotlin)} Kotlin sources; select required Java classes explicitly or supply a reviewed conversion profile")
            info["selection"] = "complete"
        info["srcs"] = sorted(sources)
        info["upstream_java_sources"] = len(original)
        info["selection_reason"] = settings.get("reason", "Complete production Java source roots")
        resources = set(settings.get("resources", []))
        for root in info["resource_roots"]:
            resources.update(p.relative_to(mps).as_posix() for p in (mps / root).rglob("*") if p.is_file())
        for path in resources:
            if not safe_path(path) or not (mps / path).is_file():
                raise ValueError(f"Invalid browser resource: {name}: {path}")
        info["resources"] = sorted(resources)
        if not set(info["exported_deps"]) <= set(info["deps"]):
            raise ValueError(f"Exported dependencies removed without updating exports: {name}")
        if not set(info["exported_libraries"]) <= set(info["libraries"]):
            raise ValueError(f"Exported libraries removed without updating exports: {name}")
        accessible, pending = set(), list(info["deps"])
        while pending:
            dependency = pending.pop()
            if dependency != name and dependency not in accessible:
                accessible.add(dependency)
                pending.extend(projects[dependency]["exported_deps"])
        info["compile_deps"] = sorted(accessible)
        libraries = set(info["libraries"])
        for dependency in accessible:
            libraries.update(projects[dependency]["exported_libraries"])
        info["compile_libraries"] = sorted(libraries)
    return {name: projects[name] for name in selected}, profile["roots"]


def artifacts(mps: Path):
    projects, roots = browser_projects(mps)
    names = sorted(projects)
    groups = compilation_groups(projects, names)
    revision = source_revision(mps)
    bzl = "# Generated by tools/inventory_browser.py from the reviewed browser profile.\n"
    bzl += f"# MPS revision: {revision}\n\n"
    # These manifests contain dictionaries, lists, strings and integers only.
    # JSON formatting keeps long strings intact; pprint splits them with implicit
    # concatenation, which is valid Python but forbidden by Starlark.
    bzl += "\n\n".join(key + " = " + json.dumps(value, indent=2)
                       for key, value in (("MPS_BROWSER_PROJECTS", projects), ("MPS_BROWSER_NAMES", names),
                                          ("MPS_BROWSER_COMPILE_GROUPS", groups))) + "\n"
    manifest = {"schema_version": 1, "mps_revision": revision, "roots": roots,
                "projects": projects, "compile_groups": groups,
                "java_sources": sum(len(p["srcs"]) for p in projects.values())}
    return bzl, json.dumps(manifest, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        bzl, manifest = artifacts(ROOT / "mps")
        valid = [write_or_check(ROOT / "mps-browser-projects.bzl", bzl, args.check),
                 write_or_check(ROOT / "compatibility/browser-projects.json", manifest, args.check)]
        result = json.loads(manifest)
        print(f"Browser profile: {len(result['projects'])} projects, {result['java_sources']} Java files, {len(result['compile_groups'])} compilation groups")
        return 0 if all(valid) else 1
    except (OSError, ValueError) as error:
        print(f"Browser inventory failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
